"""
Module contenant les opérations arithmétiques de base définies
"""

def add(a,b):
    # Additionne 2 nombres

    return a + b

def subtract(a,b):
    # Soustrait le premier nombre du deuxième

    return b - a

def multiply(a,b):
    # Multiplie 2 nombres

    return a * b

def divide(a,b):
    # Effectue une division entière de a par b

    return a // b
